CREATE TABLE security_penalties (
  id text PRIMARY KEY,
  site_id bigint NOT NULL REFERENCES sites(id),
  ip text NOT NULL,
  scope text NOT NULL,
  reason text NOT NULL,
  policy_version text NOT NULL,
  state_version integer NOT NULL DEFAULT 1,
  started_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  released_at timestamptz,
  release_kind text,
  release_reason text,
  released_by_user_id bigint REFERENCES admin_users(id),
  evidence_json jsonb NOT NULL,
  source_rule_id bigint REFERENCES blacklist_rules(id),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT security_penalties_scope_check CHECK (scope IN ('post','all')),
  CONSTRAINT security_penalties_release_kind_check CHECK (release_kind IS NULL OR release_kind IN ('revoked','released')),
  CONSTRAINT security_penalties_lifetime_check CHECK (expires_at > started_at),
  CONSTRAINT security_penalties_state_version_check CHECK (state_version > 0)
);
CREATE INDEX security_penalties_subject_idx ON security_penalties(site_id, ip, started_at);

